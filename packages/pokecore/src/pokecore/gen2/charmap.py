CRYSTAL_DIFFERENCES = MappingProxyType({
    0x14: '<PLAY_G>',
    0x15: '<MOBILE>',
})

CRYSTAL = MappingProxyType({**GOLD_SILVER, **CRYSTAL_DIFFERENCES})


def charmap(version):
    """The character map of one version (gold, silver or crystal)."""
    if version in ('gold', 'silver'):
        return GOLD_SILVER
    if version == 'crystal':
        return CRYSTAL
    raise ValueError(f'Unknown Gen II version {version!r}')
